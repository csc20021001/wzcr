function hashText(value: string) {
  let hash = 0x811c9dc5;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, '0');
}

function unitType(name: string): DepartmentSeed['unitType'] {
  if (name.includes('研究所')) return 'institute';
  if (/(學位學程|學程|學士班|碩士班|博士班|專班|MBA|EMBA)/i.test(name)) return 'program';
  if (/(學系|工程系|管理系|設計系|英文系|語文系|科技系|科學系|生物系|建築系)$/.test(name)) return 'department';
  return 'academic-unit';
}

